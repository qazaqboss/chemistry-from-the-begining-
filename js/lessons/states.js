import { h, kid, term, stage } from "../ui.js";
import { createViewer } from "../three/core.js";
import { createParticles } from "../three/particles.js";

export async function render(el) {
  el.appendChild(h(`<div>
    <p class="lead">Одно и то же вещество может быть твёрдым, жидким или газообразным. Молекулы воды во льду, в стакане и в паре <b>одинаковые</b> — разное только то, как они движутся и как далеко друг от друга находятся.</p>
  </div>`));

  const sec = h(`<section id="sim"><h2>Нагреваем воду</h2><p>Двигай ползунок температуры и смотри на молекулы H₂O в коробке.</p></section>`);
  el.appendChild(sec);
  const st = stage(`<div class="overlay"><span data-ph style="font-size:1rem"></span><span data-t></span></div>`);
  sec.appendChild(st);
  const ctl = h(`<div class="card pad" style="margin-top:10px">
    <label class="ctl">Температура: <span data-tv></span><input type="range" min="-60" max="160" step="1" value="-20"></label>
    <p data-d style="margin:10px 0 0"></p>
  </div>`);
  sec.appendChild(ctl);
  const v = createViewer(st, { camera: [6, 4, 9], autoRotateSpeed: 0.4 });
  const sim = createParticles(v, { count: 48 });
  const DESC = {
    solid: ["Лёд (твёрдое)", "Молекулы стоят на своих местах в кристаллической решётке и только дрожат. Чем теплее — тем сильнее дрожат. Твёрдое тело сохраняет форму и объём."],
    liquid: ["Вода (жидкость)", "Решётка разрушилась: молекулы скользят друг относительно друга, но остаются рядом. Жидкость сохраняет объём, но принимает форму сосуда."],
    gas: ["Пар (газ)", "Молекулы разлетелись и мчатся во все стороны, ударяясь о стенки — это и есть давление газа. Газ занимает весь предоставленный объём."],
  };
  const r = ctl.querySelector("input");
  const upd = () => {
    const t = +r.value;
    sim.setTemperature(t);
    const ph = sim.phase();
    ctl.querySelector("[data-tv]").innerHTML = `<b>${t} °C</b> · ${t + 273} K`;
    st.querySelector("[data-ph]").innerHTML = `<b>${DESC[ph][0]}</b>`;
    st.querySelector("[data-t]").textContent = `${t} °C`;
    ctl.querySelector("[data-d]").textContent = DESC[ph][1];
  };
  r.oninput = upd;
  upd();
  sec.appendChild(h(`<p class="small muted">Модель упрощённая: настоящий лёд — шестиугольная решётка, а молекул в капле в миллиарды миллиардов раз больше. Зато видно главное — характер движения.</p>`));

  el.appendChild(h(`<section id="transitions"><h2>Переходы между состояниями</h2>
    <div class="table-wrap"><table class="data">
      <tr><th>Переход</th><th>Название</th><th>Пример</th></tr>
      <tr><td>твёрдое → жидкое</td><td>плавление</td><td>лёд тает при 0 °C</td></tr>
      <tr><td>жидкое → твёрдое</td><td>кристаллизация (отвердевание)</td><td>вода замерзает</td></tr>
      <tr><td>жидкое → газ</td><td>испарение, кипение</td><td>вода кипит при 100 °C</td></tr>
      <tr><td>газ → жидкое</td><td>конденсация</td><td>роса, запотевшее зеркало</td></tr>
      <tr><td>твёрдое → газ</td><td>сублимация (возгонка)</td><td>«сухой лёд» CO₂, иод</td></tr>
      <tr><td>газ → твёрдое</td><td>десублимация</td><td>иней на окне</td></tr>
    </table></div>
    <p>Пока лёд тает, его температура <b>не растёт</b>: вся энергия уходит на разрушение решётки. То же при кипении. ${term("mp", "Температура плавления")} и ${term("bp", "кипения")} — важные характеристики вещества; у каждого элемента они указаны в таблице.</p>
    ${kid("Положи лёд в стакан с термометром: пока лёд не растает весь, термометр будет показывать 0 °C, даже если стакан стоит на солнце!")}
    <div class="callout adv">Температура кипения зависит от давления. В горах, где давление ниже, вода кипит при 85–90 °C, а в скороварке (давление выше) — при ~120 °C, поэтому еда готовится быстрее.</div>
    <div class="callout">Есть и четвёртое состояние — <b>плазма</b>: газ, раскалённый так, что электроны отрываются от атомов. Из плазмы состоят звёзды, молнии и свечение неоновых ламп.</div>
  </section>`));

  el.appendChild(h(`<section id="density"><h2>Почему лёд плавает?</h2>
    <p>Почти все вещества в твёрдом виде плотнее, чем в жидком. Вода — исключение: во льду молекулы связаны водородными связями в ажурную решётку с пустотами, поэтому лёд (0,917 г/см³) легче воды (1,000 г/см³). Благодаря этому водоёмы замерзают сверху, а рыбы зимуют подо льдом.</p>
  </section>`));
}

