import { h, kid, term, figureFrame } from "../ui.js";

export async function render(el) {
  el.appendChild(h(`<div>
    <p class="lead">Раствор — однородная смесь растворителя (чаще всего воды) и растворённого вещества. Чай с сахаром, морская вода, газировка, воздух — всё это растворы.</p>
  </div>`));

  el.appendChild(h(`<section id="dissolve"><h2>Как вещество растворяется</h2>
    <p>Молекулы воды полярны: у кислорода частичный заряд δ−, у водородов δ+. Попав в воду, кристалл соли окружается молекулами воды: «минусовые» концы тянут ионы Na⁺, «плюсовые» — ионы Cl⁻. Ионы отрываются от кристалла и уходят в раствор, окружённые «шубой» из молекул воды (гидратация).</p>
    ${kid("Вода — как толпа маленьких магнитиков. Они облепляют кусочек соли и по одной частичке растаскивают его, пока соль не «исчезнет». Но она не исчезла — попробуй воду на вкус!")}
    <h3>Растворимость</h3>
    <p>Растворимость — сколько граммов вещества может раствориться в 100 г воды при данной температуре. Для большинства твёрдых веществ она растёт с нагреванием, а для газов — падает (поэтому тёплая газировка быстрее выдыхается).</p>
    <div class="table-wrap"><table class="data">
      <tr><th>Вещество</th><th>При 20 °C, г на 100 г воды</th></tr>
      <tr><td>Сахар (сахароза)</td><td>≈ 200</td></tr>
      <tr><td>Поваренная соль NaCl</td><td>≈ 36</td></tr>
      <tr><td>Гипс CaSO₄·2H₂O</td><td>≈ 0,2</td></tr>
      <tr><td>Мел CaCO₃</td><td>≈ 0,001 (практически нерастворим)</td></tr>
    </table></div>
    <h3>Концентрация</h3>
    <div class="eq">ω = m(вещества) / m(раствора) · 100%</div>
    <p>Пример: 10 г соли в 90 г воды → ω = 10 / 100 · 100% = 10%. <span class="adv">Молярная концентрация c = n / V (моль/л) показывает, сколько моль вещества в литре раствора.</span></p>
  </section>`));

  el.appendChild(h(`<section id="acids"><h2>Кислоты и основания</h2>
    <div class="grid-2">
      <div class="card pad"><h3 class="mt0">Кислоты</h3><p class="small">В воде дают ионы водорода H⁺ (точнее, H₃O⁺). Кислые на вкус, окрашивают лакмус в красный, реагируют с металлами с выделением водорода.</p><p class="formula small">HCl → H⁺ + Cl⁻</p><p class="small muted">Соляная HCl, серная H₂SO₄, азотная HNO₃, уксусная CH₃COOH, лимонная.</p></div>
      <div class="card pad"><h3 class="mt0">Основания (щёлочи)</h3><p class="small">В воде дают гидроксид-ионы OH⁻. Мылкие на ощупь, окрашивают лакмус в синий, фенолфталеин — в малиновый.</p><p class="formula small">NaOH → Na⁺ + OH⁻</p><p class="small muted">Гидроксид натрия NaOH, гидроксид кальция Ca(OH)₂, нашатырный спирт NH₃·H₂O.</p></div>
    </div>
    <p style="margin-top:14px"><b>Нейтрализация:</b> кислота + основание → соль + вода. Ионы H⁺ и OH⁻ соединяются в воду:</p>
    <div class="eq">H⁺ + OH⁻ → H₂O &nbsp;&nbsp; (NaOH + HCl → NaCl + H₂O)</div>
    <div class="callout warn">Концентрированные кислоты и щёлочи разъедают кожу и глаза. Работать с ними можно только в очках и перчатках, под присмотром взрослых.</div>
  </section>`));

  const sec = h(`<section id="ph"><h2>Шкала pH</h2>
    <p>${term("ph", "pH")} показывает, насколько раствор кислый или щелочной: от 0 до 14. pH 7 — нейтральная среда (чистая вода), меньше 7 — кислая, больше 7 — щелочная. Каждая единица — это изменение концентрации ионов H⁺ в <b>10 раз</b>.</p>
    <p>На приборе ниже — фарфоровый планшет с каплями универсального индикатора, который меняет цвет в зависимости от pH, и pH-метр. Веди мышью по планшету или нажимай ← →.</p>
  </section>`);
  el.appendChild(sec);
  const fig = h(`<figure class="figure" style="margin:16px 0"></figure>`);
  fig.appendChild(figureFrame("figures/ph-plate", "Шкала pH — интерактивная фигура"));
  fig.appendChild(h(`<figcaption>Изометрическая фигура сделана с помощью навыка Anatomy: каждое число на ней считается той же моделью, что двигает детали.</figcaption>`));
  sec.appendChild(fig);
  sec.appendChild(h(`${kid("Сделай индикатор дома: потри краснокочанную капусту, залей горячей водой и процеди. Капни в фиолетовый отвар лимонный сок — станет розовым, а раствор соды — зелёно-синим!", "Опыт на кухне")}`));
  sec.appendChild(h(`<div class="table-wrap adv"><table class="data">
    <tr><th>Индикатор</th><th>Кислая среда</th><th>Нейтральная</th><th>Щелочная</th></tr>
    <tr><td>Лакмус</td><td style="color:#ff5d5d">красный</td><td style="color:#b07cff">фиолетовый</td><td style="color:#4dabf7">синий</td></tr>
    <tr><td>Фенолфталеин</td><td>бесцветный</td><td>бесцветный</td><td style="color:#ff4fa3">малиновый</td></tr>
    <tr><td>Метилоранж</td><td style="color:#ff5d5d">красный</td><td style="color:#ffa94d">оранжевый</td><td style="color:#ffd43b">жёлтый</td></tr>
  </table></div>`));
}

