import { h, kid, term, stage } from "../ui.js";
import { createViewer } from "../three/core.js";
import { createAirMix, createSyringe } from "../three/air-gas.js";
import { fmt } from "../chem.js";

const GASES = [
  { k: "all", label: "Весь воздух", d: "100 молекул воздуха: 78 азота, 21 кислорода и 1 аргона. Молекулы летают во все стороны и всё время сталкиваются." },
  { k: "N2", label: "Азот N₂ — 78%", d: "Азот — главный газ воздуха. Он очень «ленивый»: атомы в молекуле N₂ скреплены тройной связью, поэтому азот почти ни с чем не реагирует. Мы вдыхаем и выдыхаем его без изменений." },
  { k: "O2", label: "Кислород O₂ — 21%", d: "Кислород нужен для дыхания и горения. Его выделяют растения на свету. Без кислорода человек может прожить лишь несколько минут." },
  { k: "Ar", label: "Аргон Ar — 0,93%", d: "Аргон — благородный газ, его «молекула» — один атом. Им заполняют лампочки и используют при сварке, чтобы металл не окислялся." },
  { k: "CO2", label: "Углекислый газ CO₂ — 0,04%", d: "Углекислого газа очень мало: в настоящем воздухе одна его молекула приходится примерно на 2400 других. Здесь мы показали её одну, чтобы ты её увидел. Растения «едят» CO₂, а мы его выдыхаем." },
];

export async function render(el) {
  el.appendChild(h(`<div>
    <p class="lead">Воздух невидим, у него нет ни вкуса, ни запаха, и мы его почти не замечаем. Но это настоящее вещество — точнее, смесь газов. У воздуха есть масса, он занимает место, давит на всё вокруг и без него невозможны ни дыхание, ни огонь.</p>
    ${kid("Махни рукой — ты почувствуешь ветерок. Это ты толкнул миллиарды миллиардов крошечных частичек воздуха. Их не видно, но они повсюду: даже «пустой» стакан на самом деле полон воздуха!")}
  </div>`));

  el.appendChild(h(`<section id="real"><h2>Воздух — это вещество</h2>
    <div class="grid-2">
      <div class="card pad"><b>Воздух занимает место</b><p class="small">Засунь сухую салфетку на дно стакана и опусти стакан вверх дном в миску с водой — ровно вниз, не наклоняя. Вода не зайдёт внутрь, салфетка останется сухой: место в стакане занято воздухом. Наклони стакан — выйдет пузырь, и вода войдёт.</p></div>
      <div class="card pad"><b>У воздуха есть масса</b><p class="small">Один литр воздуха весит около 1,2 грамма. Воздух в обычной комнате (50 м³) весит примерно 60 кг — как взрослый человек! Надутый мяч чуть тяжелее сдутого: внутри больше воздуха.</p></div>
    </div>
    <p style="margin-top:14px">Воздух — это ${term("gas", "газ")}: его частицы находятся далеко друг от друга и быстро летают во все стороны. Поэтому газ заполняет любой сосуд целиком и легко сжимается.</p>
  </section>`));

  // ---------- Состав ----------
  const s2 = h(`<section id="composition"><h2>Из чего состоит воздух</h2>
    <p>Воздух — смесь нескольких газов. Если взять 100 молекул сухого воздуха, то в среднем 78 будут азотом, 21 — кислородом и 1 — аргоном. Ещё в воздухе есть водяной пар (от долей процента до 4%) и совсем немного углекислого газа.</p></section>`);
  el.appendChild(s2);
  const st = stage(`<div class="overlay"><span data-t style="font-size:1rem"></span><span>азот · кислород · аргон</span></div>`, { wide: true });
  s2.appendChild(st);
  const c2 = h(`<div class="card pad" style="margin-top:10px"><div class="chips">${GASES.map((g, i) => `<button class="chip${i ? "" : " on"}" type="button" data-k="${g.k}">${g.label}</button>`).join("")}</div><p data-d style="margin:12px 0 0"></p></div>`);
  s2.appendChild(c2);
  const v = createViewer(st, { camera: [0, 3, 12], minDistance: 5, maxDistance: 30, autoRotateSpeed: 0.4, fitWidth: 4.4 });
  const mix = createAirMix(v);
  const pick = (k) => {
    const g = GASES.find((x) => x.k === k);
    mix.focus(k);
    st.querySelector("[data-t]").innerHTML = `<b>${g.label}</b>`;
    c2.querySelector("[data-d]").textContent = g.d;
    c2.querySelectorAll("[data-k]").forEach((b) => b.classList.toggle("on", b.dataset.k === k));
  };
  c2.querySelectorAll("[data-k]").forEach((b) => (b.onclick = () => pick(b.dataset.k)));
  pick("all");
  s2.appendChild(h(`<div class="table-wrap" style="margin-top:14px"><table class="data">
    <tr><th>Газ</th><th>Формула</th><th>Доля по объёму</th><th>В 1 литре воздуха</th></tr>
    <tr><td>Азот</td><td class="formula">N₂</td><td>78,08%</td><td>781 мл</td></tr>
    <tr><td>Кислород</td><td class="formula">O₂</td><td>20,95%</td><td>210 мл</td></tr>
    <tr><td>Аргон</td><td class="formula">Ar</td><td>0,93%</td><td>9 мл</td></tr>
    <tr><td>Углекислый газ</td><td class="formula">CO₂</td><td>≈0,04%</td><td>≈0,4 мл</td></tr>
    <tr class="adv"><td>Неон, гелий, метан, криптон, водород…</td><td></td><td>&lt; 0,003%</td><td>&lt; 0,03 мл</td></tr>
  </table></div>`));

  // ---------- Кислород и CO₂ ----------
  el.appendChild(h(`<section id="o2co2"><h2>Кислород и углекислый газ</h2>
    <p>Когда мы дышим, клетки тела «сжигают» питательные вещества с помощью ${term("oxygen", "кислорода")} и получают энергию. При этом образуются вода и углекислый газ, который мы выдыхаем. Во вдыхаемом воздухе около 21% кислорода, а в выдыхаемом — около 16%, зато углекислого газа в выдохе примерно 4% — в 100 раз больше, чем в воздухе вокруг.</p>
    <div class="eq">сахар + кислород → углекислый газ + вода + энергия</div>
    <p>Растения делают обратное: на свету они забирают из воздуха углекислый газ и воду и строят из них сахар, выделяя кислород. Это <b>фотосинтез</b>. Весь кислород в атмосфере Земли сделан растениями и водорослями!</p>
    <div class="eq">6CO₂ + 6H₂O —(свет)→ C₆H₁₂O₆ + 6O₂</div>
    <div class="grid-2">
      <div class="card pad"><b>Свойства кислорода</b><p class="small">Бесцветный газ без запаха, чуть тяжелее воздуха. Сам не горит, но поддерживает горение: тлеющая лучинка в чистом кислороде вспыхивает ярким пламенем.</p></div>
      <div class="card pad"><b>Свойства углекислого газа</b><p class="small">Бесцветный, в 1,5 раза тяжелее воздуха — его можно «переливать» из стакана в стакан. Горение не поддерживает: им тушат огонь. Это он делает газировку шипучей.</p></div>
    </div>
    <p class="adv" style="margin-top:12px">Узнать углекислый газ можно по помутнению <b>известковой воды</b> (раствора Ca(OH)₂): выдохни в неё через трубочку — она станет мутной, выпадет мел: Ca(OH)₂ + CO₂ → CaCO₃↓ + H₂O.</p>
  </section>`));

  // ---------- Давление ----------
  const s4 = h(`<section id="pressure"><h2>Давление газа: шприц</h2>
    <p>Молекулы газа всё время ударяются о стенки сосуда. Каждый удар крошечный, но их миллиарды миллиардов в секунду — и вместе они давят на стенку. Это и есть ${term("gaspressure", "давление газа")}. Закрой пальцем носик шприца и нажми на поршень: чем сильнее сжимаешь воздух, тем сильнее он упирается в ответ.</p></section>`);
  el.appendChild(s4);
  const st4 = stage(`<div class="overlay"><span data-v style="font-size:1rem"></span><span data-p></span></div>`, { wide: true });
  s4.appendChild(st4);
  const c4 = h(`<div class="card pad" style="margin-top:10px">
    <label class="ctl">Объём воздуха в шприце: <b data-vv></b><input type="range" min="25" max="100" step="5" value="100"></label>
    <label class="row small" style="margin-top:10px"><input type="checkbox" data-hot> Нагреть шприц с 20 °C до 100 °C</label>
    <p data-d class="small" style="margin:10px 0 0"></p></div>`);
  s4.appendChild(c4);
  const v4 = createViewer(st4, { camera: [0, 2.5, 13], minDistance: 6, maxDistance: 30, autoRotate: false, fitWidth: 6.8 });
  const syr = createSyringe(v4);
  const range = c4.querySelector("input[type=range]"), hot = c4.querySelector("[data-hot]");
  let base = 0;
  const upd = () => {
    const V = +range.value, T = hot.checked ? 373 : 293;
    syr.set(V / 100, hot.checked);
    const p = (100 / V) * (T / 293);
    c4.querySelector("[data-vv]").textContent = `${V} мл`;
    st4.querySelector("[data-v]").innerHTML = `<b>${V} мл · ${hot.checked ? 100 : 20} °C</b>`;
    st4.querySelector("[data-p]").innerHTML = `давление ≈ <b>${fmt(p, 2)} атм</b>`;
    c4.querySelector("[data-d]").textContent = V < 100 ? `Объём уменьшился в ${fmt(100 / V, 2)} раза — молекулам тесно, они чаще бьют в поршень, и давление выросло во столько же раз${hot.checked ? ", а нагрев добавил ещё: горячие молекулы летают быстрее и бьют сильнее" : ""}.` : hot.checked ? "Горячие молекулы летают быстрее и бьют в поршень чаще и сильнее — давление растёт даже без сжатия." : "Сдвинь ползунок — сожми воздух поршнем.";
  };
  range.oninput = upd; hot.onchange = upd; upd();
  const hitEl = h(`<p class="small muted" style="margin:6px 0 0"></p>`);
  c4.appendChild(hitEl);
  v4.onFrame((dt, t) => { if (t - base > 0.5) { base = t; hitEl.textContent = `Счётчик в модели: ${fmt(syr.rate(), 0)} ударов молекул о поршень за секунду.`; } });
  s4.appendChild(h(`<div class="callout adv"><b>Закон Бойля — Мариотта:</b> при постоянной температуре давление газа обратно пропорционально объёму: p₁V₁ = p₂V₂. Сжали воздух в 2 раза — давление выросло в 2 раза. А при нагреве в закрытом сосуде давление растёт пропорционально абсолютной температуре (в кельвинах): 373 K / 293 K ≈ 1,27.</div>`));

  el.appendChild(h(`<section id="atmosphere"><h2>Атмосферное давление</h2>
    <p>Над нами — океан воздуха высотой в сотни километров. Он давит на всё с силой около 10 ньютонов на каждый квадратный сантиметр — как будто на ноготь поставили гирьку в 1 кг. Мы этого не чувствуем, потому что воздух внутри нас давит в ответ так же сильно. Нормальное атмосферное давление — 101 325 Па, или 760 мм ртутного столба.</p>
    <ul>
      <li><b>Трубочка для сока.</b> Ты не «всасываешь» сок: ты убираешь воздух из трубочки, и атмосфера вталкивает сок тебе в рот.</li>
      <li><b>Присоска</b> держится, потому что под ней воздуха почти нет, а снаружи атмосфера прижимает её к стеклу.</li>
      <li><b>В горах</b> воздух реже, давление ниже — вода кипит не при 100 °C, а, около 83 °C на высоте 5 км.</li>
    </ul>
    <div class="card pad"><b>Опыт: волшебная открытка</b><p class="small" style="margin:0">Налей стакан воды до краёв, накрой открыткой, прижми ладонью и переверни над раковиной. Убери руку — вода не выливается! Давление воздуха снизу на открытку больше, чем давление воды сверху.</p></div>
    ${kid("На тебя всё время давит воздух — как будто ты на дне огромного невидимого океана. Но тебе не тяжело: внутри тебя тоже есть воздух, и он толкает наружу с той же силой.")}
  </section>`));
}

