import { h, kid, term, figureFrame } from "../ui.js";

export async function render(el) {
  el.appendChild(h(`<div>
    <p class="lead">${term("oxidation", "Окислительно-восстановительные реакции")} (ОВР) — реакции, в которых электроны переходят от одних атомов к другим. Горение, ржавление, дыхание, фотосинтез, работа батарейки — всё это ОВР.</p>
  </div>`));

  el.appendChild(h(`<section id="ox"><h2>Степень окисления</h2>
    <p>Степень окисления — условный заряд атома, если считать, что все связи ионные. Правила:</p>
    <ul>
      <li>У простых веществ — 0 (Fe, O₂, H₂).</li>
      <li>Водород обычно +1, кислород обычно −2, фтор всегда −1.</li>
      <li>Щелочные металлы +1, щёлочноземельные +2.</li>
      <li>Сумма степеней окисления в молекуле равна 0, в ионе — заряду иона.</li>
    </ul>
    <div class="eq">H⁺¹₂S⁺⁶O⁻²₄ : 2·(+1) + 6 + 4·(−2) = 0</div>
    <h3>Кто отдаёт, кто берёт</h3>
    <div class="grid-2">
      <div class="card pad"><b>Восстановитель</b> отдаёт электроны — сам <b>окисляется</b> (степень окисления растёт).<p class="formula small" style="margin-top:8px">Zn⁰ − 2e⁻ → Zn⁺²</p></div>
      <div class="card pad"><b>Окислитель</b> принимает электроны — сам <b>восстанавливается</b> (степень окисления уменьшается).<p class="formula small" style="margin-top:8px">Cu⁺² + 2e⁻ → Cu⁰</p></div>
    </div>
    ${kid("Восстановитель — щедрый друг, раздающий электроны. Окислитель — коллекционер, который их собирает. Сколько один отдал, столько другой и забрал!")}
    <p style="margin-top:12px">Опыт: железный гвоздь в растворе медного купороса покрывается красной медью. Железо отдаёт электроны ионам меди:</p>
    <div class="eq">Fe⁰ + Cu⁺²SO₄ → Fe⁺²SO₄ + Cu⁰</div>
  </section>`));

  const sec = h(`<section id="electrolysis"><h2>Электролиз воды</h2>
    <p>Если пропустить постоянный ток через воду (с добавкой соли или щёлочи для проводимости), она разлагается на водород и кислород. На <b>катоде</b> (−) ионы получают электроны и выделяется водород, на <b>аноде</b> (+) отдают электроны — выделяется кислород.</p>
    <div class="eq">2H₂O → 2H₂↑ + O₂↑</div>
    <p>Водорода всегда получается ровно в <b>два раза больше</b> по объёму, чем кислорода, — это прямо видно по уравнению: 2 молекулы H₂ на 1 молекулу O₂. Покрути ручку источника тока на приборе Гофмана:</p>
  </section>`);
  el.appendChild(sec);
  const fig = h(`<figure class="figure" style="margin:16px 0"></figure>`);
  fig.appendChild(figureFrame("figures/electrolysis", "Электролиз воды — прибор Гофмана"));
  fig.appendChild(h(`<figcaption>Прибор Гофмана в изометрии (навык Anatomy). Ниже ~1,8 В электролиз практически не идёт: теоретический минимум 1,23 В, а на электродах нужен ещё «перенапряжение».</figcaption>`));
  sec.appendChild(fig);
  sec.appendChild(h(`<div class="callout adv">Процессы на электродах: катод (−): 4H₂O + 4e⁻ → 2H₂ + 4OH⁻; анод (+): 2H₂O − 4e⁻ → O₂ + 4H⁺. Электролизом получают алюминий, хлор, щёлочи, чистую медь, наносят гальванические покрытия.</div>`));

  el.appendChild(h(`<section id="battery"><h2>Батарейка — ОВР наоборот</h2>
    <p>Электролиз использует ток, чтобы провести реакцию. А гальванический элемент (батарейка) делает обратное: самопроизвольная ОВР даёт ток. В элементе Даниэля цинк отдаёт электроны, они бегут по проводу к меди — и по пути зажигают лампочку.</p>
    <div class="eq">Zn + CuSO₄ → ZnSO₄ + Cu &nbsp;&nbsp; (≈ 1,1 В)</div>
    ${kid("Воткни в лимон медную монетку и оцинкованный гвоздь, соедини проводками — получится настоящая батарейка! Несколько лимонов вместе могут зажечь маленький светодиод.", "Опыт")}
  </section>`));
}

