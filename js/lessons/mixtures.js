const METHODS = ["магнит", "отстаивание", "фильтрование", "выпаривание", "перегонка", "хроматография"];

export async function render(el) {
  el.appendChild(h(`<div>
    <p class="lead">В природе почти не бывает совершенно чистых веществ. Морская вода, воздух, молоко, гранит, почва — всё это ${term("mixture", "смеси")}. Химики умеют разделять смеси, используя то, что вещества в них отличаются свойствами.</p>
    ${kid("Представь, что в коробке перемешались пуговицы, скрепки и крупа. Как их разобрать? Скрепки соберёт магнит, крупу можно просеять через сито, а пуговицы останутся. Химики делают то же самое — только с веществами!")}
  </div>`));

  el.appendChild(h(`<section id="pure"><h2>Чистые вещества и смеси</h2>
    <p>${term("puresub", "Чистое вещество")} состоит из одинаковых частиц и имеет постоянные свойства: дистиллированная вода всегда кипит при 100 °C (на уровне моря) и замерзает при 0 °C. Смесь — это несколько веществ вместе; каждое сохраняет в ней свои свойства. Солёная вода кипит выше 100 °C, а замерзает ниже 0 °C.</p>
    <div class="grid-2">
      <div class="card pad"><b>Неоднородные смеси</b><p class="small">Части видно глазом или в лупу: песок в воде, масло на воде, гранит (розовые, серые и чёрные зёрна), салат, дым, туман.</p></div>
      <div class="card pad"><b>Однородные смеси</b><p class="small">Частицы перемешаны до отдельных молекул, никакой микроскоп их не различит: сладкий чай, морская вода, воздух, уксус, сплавы металлов (бронза, сталь).</p></div>
    </div>
    <p style="margin-top:14px">Однородную жидкую смесь называют <b>раствором</b>. В растворе соли вода — <i>растворитель</i>, соль — <i>растворённое вещество</i>.</p>
  </section>`));

  // ---------- 3D ----------
  const sec = h(`<section id="separate"><h2>Разделяем смесь по шагам</h2>
    <p>Давай разделим смесь из четырёх веществ: воды, соли, песка и железных опилок. Нажимай кнопки по порядку и следи за частицами. Фиолетовые шарики — ионы натрия Na⁺, зелёные — ионы хлора Cl⁻.</p></section>`);
  el.appendChild(sec);
  const st = stage(`<div class="overlay"><span data-t style="font-size:1rem"></span><span>песок · железо · <span style="color:#ab5cf2">Na⁺</span> · <span style="color:#2fd35b">Cl⁻</span></span></div>`, { wide: true });
  sec.appendChild(st);
  const ctl = h(`<div class="card pad" style="margin-top:10px">
    <div class="chips">${STEPS.map((s, i) => `<button class="chip${i ? "" : " on"}" type="button" data-s="${i}">${i ? s.t : "↺ Смесь"}</button>`).join("")}</div>
    <p data-d style="margin:12px 0 0"></p>
  </div>`);
  sec.appendChild(ctl);
  const v = createViewer(st, { camera: [0, 3, 13], target: [0, 0.6, 0], minDistance: 6, maxDistance: 30, autoRotate: false, fitWidth: 4.8 });
  const sep = createSeparation(v);
  const show = (i) => {
    sep.go(i, i === 0);
    st.querySelector("[data-t]").innerHTML = `<b>${STEPS[i].t}</b>`;
    ctl.querySelector("[data-d]").textContent = STEPS[i].d;
    ctl.querySelectorAll("[data-s]").forEach((b) => b.classList.toggle("on", +b.dataset.s === i));
  };
  ctl.querySelectorAll("[data-s]").forEach((b) => (b.onclick = () => show(+b.dataset.s)));
  show(0);
  sec.appendChild(h(`<div class="callout"><b>Почему порядок важен?</b> Если сначала выпарить воду, песок, соль и опилки останутся одной сухой кучкой. А если сначала отфильтровать, опилки застрянут на фильтре вместе с песком. Хороший химик продумывает план разделения заранее.</div>`));

  el.appendChild(h(`<section id="methods"><h2>Способы разделения</h2>
    <p>Каждый способ основан на каком-то <b>различии в свойствах</b> веществ смеси:</p>
    <div class="table-wrap"><table class="data">
      <tr><th>Способ</th><th>На каком различии основан</th><th>Пример</th></tr>
      <tr><td>Действие магнитом</td><td>одно вещество притягивается магнитом</td><td>железо из песка</td></tr>
      <tr><td>Отстаивание</td><td>разная плотность, вещество не растворяется</td><td>глина в воде, масло и вода</td></tr>
      <tr><td>${term("filtration", "Фильтрование")}</td><td>размер частиц: крупные застревают в порах фильтра</td><td>песок и вода, заварка в чайнике</td></tr>
      <tr><td>${term("evaporation", "Выпаривание")}</td><td>одно вещество испаряется, другое — нет</td><td>соль из морской воды</td></tr>
      <tr><td>${term("distillation", "Перегонка")}</td><td>разные температуры кипения</td><td>чистая вода, бензин из нефти</td></tr>
      <tr><td>Хроматография</td><td>разная «цепкость» к бумаге или порошку</td><td>красители в чернилах, анализ крови</td></tr>
    </table></div>
    <div class="card pad" style="margin-top:14px"><b>Опыт: радуга из фломастера</b>
      <ol class="small">
        <li>Отрежь полоску бумажного полотенца или фильтра для кофе.</li>
        <li>В 2 см от края поставь жирную точку <b>чёрным</b> водорастворимым фломастером.</li>
        <li>Опусти край полоски в стакан с небольшим количеством воды так, чтобы точка была выше воды.</li>
        <li>Подожди 10–15 минут.</li>
      </ol>
      <p class="small" style="margin:0">Вода поднимается по бумаге и тащит за собой краски. Одни краски «цепляются» за бумагу сильнее и отстают, другие убегают вперёд. Чёрная точка распадается на синюю, фиолетовую, жёлтую полоски: чёрный цвет оказался смесью!</p>
    </div>
  </section>`));

  // ---------- Перегонка ----------
  const sd = h(`<section id="distillation"><h2>Перегонка</h2>
    <p>Перегонка (дистилляция) разделяет жидкости или очищает воду. Смесь нагревают в колбе. Вещество, которое кипит при более низкой температуре, первым превращается в пар. Пар идёт по трубке через холодильник — трубку, вокруг которой течёт холодная вода, — и снова становится жидкостью (${term("condensation", "конденсируется")}). Капли стекают в приёмник. Всё, что не испарилось, остаётся в колбе.</p>
  </section>`);
  el.appendChild(sd);
  const fig = h(`<figure class="figure" style="margin:16px 0"></figure>`);
  fig.appendChild(figureFrame("figures/distillation", "Перегонка — прибор для разделения жидкостей"));
  fig.appendChild(h(`<figcaption>Прибор для перегонки: колба с термометром, холодильник Либиха (вода в рубашке течёт снизу вверх — навстречу пару) и приёмник.</figcaption>`));
  sd.appendChild(fig);
  sd.appendChild(h(`<p>Так получают <b>дистиллированную воду</b> для аптек и лабораторий, разделяют нефть на бензин, керосин и мазут, опресняют морскую воду на кораблях. Дождь — это природная перегонка: солнце испаряет воду из моря, а соль остаётся в море.</p>`));
  sd.appendChild(h(kid("Подержи над кастрюлей с кипящей водой холодную крышку — на ней появятся капли. Это и есть перегонка: пар охладился и снова стал водой. Только делай это со взрослыми — пар обжигает!", "Перегонка на кухне")));

  // ---------- Тренажёр ----------
  const sec5 = h(`<section id="choose"><h2>Тренажёр: какой способ выбрать?</h2>
    <p>Для каждой смеси выбери лучший способ разделения.</p>
    <div class="mx-tasks" style="display:grid;gap:10px"></div>
    <p class="mx-score small muted" aria-live="polite"></p>
  </section>`);
  el.appendChild(sec5);
  {
    const box = sec5.querySelector(".mx-tasks");
    let done = 0, ok = 0;
    TASKS.forEach((t) => {
      const row = h(`<div class="card pad"><b>${t.m}</b><div class="chips" style="margin-top:8px">${METHODS.map((m) => `<button class="chip" type="button">${m}</button>`).join("")}</div><p class="small" style="margin:8px 0 0" hidden></p></div>`);
      row.querySelectorAll(".chip").forEach((b) => (b.onclick = () => {
        if (row.dataset.done) return;
        row.dataset.done = 1; done++;
        const right = b.textContent === t.a;
        if (right) ok++;
        row.querySelectorAll(".chip").forEach((x) => { if (x.textContent === t.a) x.classList.add("on"); });
        const p = row.querySelector("p"); p.hidden = false;
        p.innerHTML = (right ? "<b style='color:var(--good)'>Верно!</b> " : `<b style='color:var(--bad)'>Лучше — ${t.a}.</b> `) + t.why;
        if (done === TASKS.length) sec5.querySelector(".mx-score").textContent = `Правильно ${ok} из ${TASKS.length}.`;
      }));
      box.appendChild(row);
    });
  }

  el.appendChild(h(`<section id="around"><h2>Смеси вокруг нас</h2>
    <ul>
      <li><b>Воздух</b> — однородная смесь газов: азота, кислорода, аргона, углекислого газа и водяного пара.</li>
      <li><b>Молоко</b> — капельки жира и белки, рассеянные в воде. Если молоко постоит, сверху соберутся сливки — это отстаивание.</li>
      <li><b>Нефть</b> — смесь сотен веществ. На заводе её разгоняют перегонкой в высоких колоннах.</li>
      <li><b>Кровь</b> — в центрифуге (быстро вращающемся приборе) делится на клетки и жидкую плазму.</li>
      <li><b>Водопровод</b>: воду из реки отстаивают, фильтруют через песок и уголь и обеззараживают.</li>
    </ul>
    <div class="callout warn"><b>Важно:</b> отличай смесь от химической реакции. Если смешать железные опилки и серу, их можно снова разделить магнитом. Но если смесь нагреть, получится новое вещество — сульфид железа FeS, — которое магнитом уже не разделить.</div>
  </section>`));
}

