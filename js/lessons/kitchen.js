import { h, kid, term, stage } from "../ui.js";
import { createViewer } from "../three/core.js";
import { createFizz, createCaramel, M_SODA, M_ACID, VM } from "../three/kitchen-fizz.js";
import { fmt } from "../chem.js";

const CARAMEL = [
  [20, "Обычный сахар: белые кристаллики сахарозы."],
  [160, "Сахар начинает плавиться и разрушаться. Пока он почти бесцветный."],
  [170, "Светлая карамель: молекулы сахарозы распадаются на глюкозу и фруктозу и теряют воду (видишь пар?)."],
  [180, "Золотистая карамель: из осколков молекул собираются новые — сотни разных веществ. Появляются цвет и тот самый карамельный запах."],
  [190, "Тёмная карамель: вкус горчит, цвет янтарный. Здесь пора снимать с огня!"],
  [205, "Сахар горит и обугливается: остаётся углерод (чёрный) и едкий дым. Это уже необратимо испорчено."],
];

export async function render(el) {
  el.appendChild(h(`<div>
    <p class="lead">Кухня — настоящая химическая лаборатория. Когда мы печём, жарим, варим и даже режем яблоко, вещества превращаются в другие вещества. Повара — это химики, которые знают, какие реакции делают еду вкусной.</p>
    ${kid("Сварить яйцо, испечь блинчик, поджарить хлеб — это химические реакции! Назад их не повернуть: из омлета снова не сделаешь сырое яйцо.")}
    <div class="callout warn"><b>Важно:</b> опыты на кухне — только со взрослыми. Уксус щиплет глаза, горячая карамель обжигает сильнее кипятка (она горячее 150 °C и липнет к коже).</div>
  </div>`));

  el.appendChild(h(`<section id="changes"><h2>Физические и химические явления</h2>
    <div class="grid-2">
      <div class="card pad"><b>Физическое явление</b> — вещество остаётся тем же, меняется только форма или состояние.<p class="small">Масло тает, сахар растворяется в чае, вода кипит, хлеб режут на ломтики.</p></div>
      <div class="card pad"><b>${term("chemreaction", "Химическое явление")}</b> — образуются новые вещества.<p class="small">Хлеб поджаривается, молоко скисает, яйцо сворачивается, сода шипит с уксусом, яблоко темнеет.</p></div>
    </div>
    <p style="margin-top:12px">Признаки химической реакции: выделяется газ (пузырьки), меняется цвет, появляется запах, выпадает осадок, выделяется тепло или свет.</p>
  </section>`));

  // ---------- Сода и уксус ----------
  const s2 = h(`<section id="soda"><h2>Сода и уксус: надуваем шарик</h2>
    <p>Пищевая сода — это гидрокарбонат натрия NaHCO₃. Столовый уксус — 9%-й раствор уксусной кислоты CH₃COOH в воде. Когда они встречаются, начинается бурная реакция, и выделяется <b>углекислый газ</b>:</p>
    <div class="eq">NaHCO₃ + CH₃COOH → CH₃COONa + H₂O + CO₂↑</div>
    <p>Положи соду в бутылку с уксусом, надень на горлышко шарик — газ его надует. Добавляй соду и уксус и смотри, как сработает реакция.</p></section>`);
  el.appendChild(s2);
  const st = stage(`<div class="overlay"><span data-a style="font-size:1rem"></span><span data-b></span></div>`, { wide: true });
  s2.appendChild(st);
  const c2 = h(`<div class="card pad" style="margin-top:10px">
    <div class="row"><button class="btn" type="button" data-soda>🥄 + 1 чайная ложка соды (5 г)</button><button class="btn" type="button" data-vin>🧴 + 50 мл уксуса 9%</button><button class="btn small" type="button" data-reset>↺ Сначала</button></div>
    <div class="table-wrap" style="margin-top:10px"><table class="data"><tr><th>Сода осталось</th><th>Кислоты осталось</th><th>CO₂ получено</th></tr><tr><td data-s1></td><td data-s2></td><td data-s3></td></tr></table></div>
    <p data-d class="small" style="margin:8px 0 0"></p></div>`);
  s2.appendChild(c2);
  const v = createViewer(st, { camera: [0, 1.5, 13], target: [0, 0.6, 0], minDistance: 6, maxDistance: 30, autoRotateSpeed: 0.4, fitWidth: 3.6 });
  const fz = createFizz(v);
  const S = fz.state;
  fz.addVinegar(50);
  c2.querySelector("[data-soda]").onclick = () => fz.addSoda(5);
  c2.querySelector("[data-vin]").onclick = () => fz.addVinegar(50);
  c2.querySelector("[data-reset]").onclick = () => { fz.reset(); fz.addVinegar(50); };
  const upd = () => {
    const g = (n, M) => `${fmt(n * M, 2)} г`;
    c2.querySelector("[data-s1]").textContent = g(S.soda, M_SODA);
    c2.querySelector("[data-s2]").textContent = g(S.acid, M_ACID);
    c2.querySelector("[data-s3]").textContent = `${fmt(S.co2, 3)} моль ≈ ${fmt(S.co2 * VM, 2)} л`;
    st.querySelector("[data-a]").innerHTML = `<b>${S.rate > 0.002 ? "Шшш! Идёт реакция" : S.co2 > 0 ? "Реакция закончилась" : "Уксус в бутылке"}</b>`;
    st.querySelector("[data-b]").textContent = `уксуса ${fmt(S.vol, 0)} мл`;
    let d = "Добавь ложку соды.";
    if (S.rate <= 0.002 && S.co2 > 0) d = S.soda > 1e-4 ? "Кислота кончилась — на дне лежит лишняя сода. Долей уксуса, и шипение начнётся снова!" : S.acid > 1e-4 ? "Сода кончилась, а кислота ещё осталась. Добавь соды — шарик надуется ещё." : "Всё прореагировало без остатка.";
    else if (S.rate > 0.002) d = "Пузырьки — это углекислый газ. Он поднимается вверх и надувает шарик.";
    c2.querySelector("[data-d]").textContent = d;
  };
  let acc = 0;
  v.onFrame((dt) => { acc += dt; if (acc > 0.2) { acc = 0; upd(); } });
  upd();
  s2.appendChild(h(`<div class="callout adv"><b>Расчёт.</b> 5 г соды — это 5 / 84 ≈ 0,060 моль NaHCO₃. 50 мл 9%-го уксуса содержат ≈ 4,5 г кислоты = 4,5 / 60 ≈ 0,076 моль. Реагируют они 1 : 1, поэтому соды не хватит раньше (она в «недостатке»), и получится 0,060 моль CO₂ — примерно 1,4 литра газа при комнатной температуре (1 моль газа ≈ 24 л). Немного CO₂ растворится в воде, поэтому настоящий шарик будет чуть меньше.</div>`));
  s2.appendChild(h(`<div class="card pad"><b>Опыт: капустный индикатор</b><p class="small" style="margin:0">Со взрослым мелко нарежь краснокочанную капусту и залей горячей водой на 15 минут. Процеди — получится фиолетовый отвар. Капни в него уксуса — он станет розово-красным, а щепотка соды сделает его зелёно-синим. Красители капусты (антоцианы) меняют цвет в кислой и щелочной среде — это природный ${term("ph", "индикатор кислотности")}.</p></div>`));

  // ---------- Тесто ----------
  el.appendChild(h(`<section id="dough"><h2>Почему тесто пышное</h2>
    <p>Пышный хлеб и пирог полны дырочек — это пузырьки газа, застрявшие в тесте. Откуда газ?</p>
    <div class="grid-2">
      <div class="card pad"><b>Дрожжи</b><p class="small">Дрожжи — живые одноклеточные грибки. Они «едят» сахар и выдыхают углекислый газ, а ещё выделяют немного спирта (он улетучивается при выпечке). Это ${term("fermentation", "брожение")}:</p><p class="formula small">C₆H₁₂O₆ → 2C₂H₅OH + 2CO₂↑</p><p class="small">Дрожжам нужно тепло (25–35 °C): в холоде они «спят», а в кипятке погибают.</p></div>
      <div class="card pad"><b>Разрыхлитель и сода</b><p class="small">Разрыхлитель — это сода, смешанная с сухой кислотой (например, лимонной) и мукой. Пока он сухой — ничего не происходит. В мокром тесте и в духовке кислота встречается с содой, и выделяется CO₂ — тот же, что в нашей бутылке.</p></div>
    </div>
    <p style="margin-top:12px">В горячей духовке пузырьки газа расширяются, а белки муки и яиц твердеют и «запирают» их внутри. Поэтому готовый хлеб не опадает.</p>
    ${kid("Положи в бутылку с тёплой водой ложку сахара и пакетик сухих дрожжей, надень шарик. Через полчаса шарик начнёт надуваться — это дрожжи «дышат» углекислым газом!", "Опыт: дрожжи надувают шарик")}
  </section>`));

  // ---------- Карамель ----------
  const s4 = h(`<section id="caramel"><h2>Карамель</h2>
    <p>Если нагревать сахар без воды, при 160–180 °C он плавится и превращается в карамель. Это не простое плавление: молекулы сахарозы C₁₂H₂₂O₁₁ разваливаются, теряют воду и складываются в сотни новых веществ — коричневых, ароматных и горьковатых. Такое превращение называют ${term("caramelization", "карамелизацией")}.</p></section>`);
  el.appendChild(s4);
  const st4 = stage(`<div class="overlay"><span data-t style="font-size:1rem"></span><span data-sw></span></div>`, { wide: true });
  s4.appendChild(st4);
  const c4 = h(`<div class="card pad" style="margin-top:10px"><label class="ctl">Температура сковороды: <b data-tv></b><input type="range" min="20" max="215" step="1" value="20"></label><p data-d style="margin:10px 0 0"></p></div>`);
  s4.appendChild(c4);
  const v4 = createViewer(st4, { camera: [0, 5, 8], target: [0, 0, 0], minDistance: 4, maxDistance: 20, autoRotateSpeed: 0.3, fitWidth: 4.2 });
  const car = createCaramel(v4);
  const ti = c4.querySelector("input");
  const updC = () => {
    const T = +ti.value;
    car.set(T);
    const row = [...CARAMEL].reverse().find(([t]) => T >= t);
    c4.querySelector("[data-tv]").textContent = `${T} °C`;
    c4.querySelector("[data-d]").textContent = row[1];
    st4.querySelector("[data-t]").innerHTML = `<b>${T} °C</b>`;
    st4.querySelector("[data-sw]").innerHTML = `<span style="display:inline-block;width:14px;height:14px;border-radius:4px;vertical-align:middle;background:#${car.color(T).getHexString()};border:1px solid var(--line-2)"></span> цвет`;
  };
  ti.oninput = updC; updC();
  s4.appendChild(h(`<p>Похожая, но другая реакция — <b>реакция Майяра</b>: сахара реагируют с белками. Она даёт румяную корочку хлеба, жареного мяса и аромат кофе. Корочка коричневая, а мякиш внутри — светлый: там температура не поднимается выше 100 °C, пока есть вода.</p>`));

  // ---------- Яблоко ----------
  el.appendChild(h(`<section id="apple"><h2>Почему яблоко темнеет</h2>
    <p>Разрежь яблоко — через 10–20 минут срез станет коричневым. В клетках яблока есть особые вещества (полифенолы) и белок-помощник — фермент. Пока клетки целые, они хранятся отдельно. Нож разрушает клетки, фермент встречается с полифенолами и с <b>кислородом воздуха</b> и быстро превращает их в коричневые пигменты. То же происходит с бананом, картошкой и авокадо.</p>
    <div class="card pad"><b>Опыт: три дольки</b>
      <ol class="small"><li>Нарежь яблоко на три дольки.</li><li>Первую оставь на тарелке, вторую сбрызни лимонным соком, третью опусти в стакан с водой.</li><li>Сравни через 30 минут.</li></ol>
      <p class="small" style="margin:0">Первая потемнеет. Вода закрыла третью дольку от кислорода — она останется светлой. Лимонный сок кислый, и фермент в кислоте работает плохо; к тому же витамин C в соке перехватывает кислород. Поэтому вторая долька тоже почти не темнеет.</p>
    </div>
    ${kid("Яблоко «загорает» не от солнца, а от воздуха! Лимонный сок — как крем от загара для яблока.")}
  </section>`));
}

