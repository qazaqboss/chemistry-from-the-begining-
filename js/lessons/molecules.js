import { h, kid, term } from "../ui.js";
import { moleculeExplorer } from "../lab.js";

export async function render(el) {
  el.appendChild(h(`<div>
    <p class="lead">Форма ${term("molecule", "молекулы")} определяет её свойства: почему вода жидкая и растворяет соль, а углекислый газ — газ. Форму можно предсказать одной простой идеей.</p>
  </div>`));

  el.appendChild(h(`<section id="vsepr"><h2>Пары электронов отталкиваются</h2>
    <p>Вокруг центрального атома есть электронные пары — связи и неподелённые пары. Все они заряжены отрицательно и <b>отталкиваются</b>, поэтому располагаются как можно дальше друг от друга. Это теория отталкивания электронных пар (VSEPR, или теория Гиллеспи).</p>
    ${kid("Привяжи к одной точке несколько воздушных шариков — они сами разойдутся в разные стороны. Два шарика встанут в линию, три — треугольником, четыре — пирамидкой-тетраэдром. Так же ведут себя электроны!")}
    <div class="table-wrap"><table class="data">
      <tr><th>Пар всего</th><th>Из них неподелённых</th><th>Форма</th><th>Угол</th><th>Пример</th></tr>
      <tr><td>2</td><td>0</td><td>линейная</td><td>180°</td><td>CO₂, BeCl₂</td></tr>
      <tr><td>3</td><td>0</td><td>плоский треугольник</td><td>120°</td><td>BF₃</td></tr>
      <tr><td>4</td><td>0</td><td>тетраэдр</td><td>109,5°</td><td>CH₄</td></tr>
      <tr><td>4</td><td>1</td><td>тригональная пирамида</td><td>107°</td><td>NH₃</td></tr>
      <tr><td>4</td><td>2</td><td>угловая</td><td>104,5°</td><td>H₂O</td></tr>
      <tr class="adv"><td>5</td><td>0</td><td>тригональная бипирамида</td><td>90°, 120°</td><td>PCl₅</td></tr>
      <tr class="adv"><td>6</td><td>0</td><td>октаэдр</td><td>90°</td><td>SF₆</td></tr>
      <tr class="adv"><td>6</td><td>2</td><td>плоский квадрат</td><td>90°</td><td>XeF₄</td></tr>
    </table></div>
    <p>Неподелённая пара занимает больше места, чем связь, поэтому у аммиака угол 107°, а у воды — 104,5° вместо «идеальных» 109,5°.</p>
  </section>`));

  const sec = h(`<section id="gallery"><h2>Галерея молекул</h2><p>Выбери молекулу, крути её и переключай модель: <b>шаростержневая</b> показывает связи и углы, <b>заполненная</b> — реальный «объём» атомов.</p></section>`);
  el.appendChild(sec);
  moleculeExplorer(sec, ["H2O", "CO2", "NH3", "CH4", "BF3", "O3", "PCl5", "SF6", "XeF4", "CH2O", "HCN", "H2O2"]);

  el.appendChild(h(`<section id="polar"><h2>Полярность молекулы</h2>
    <p>Даже если связи полярны, молекула может быть неполярной — если её форма симметрична и «перетягивания» гасят друг друга. В CO₂ два кислорода тянут электроны в противоположные стороны — молекула неполярна. В изогнутой воде — не гасят: у молекулы есть «плюсовой» и «минусовой» концы (диполь).</p>
    <div class="callout good">Поэтому вода так хорошо растворяет соли и сахар, а масло (неполярное) с водой не смешивается: «подобное растворяется в подобном».</div>
  </section>`));
}

