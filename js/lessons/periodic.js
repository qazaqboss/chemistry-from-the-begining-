import { h, kid, term, stage, chips } from "../ui.js";
import { createViewer } from "../three/core.js";
import { createTable3D, PROPS3D } from "../three/table3d.js";
import { CAT_NAMES } from "../periodic-layout.js";
import { fmt } from "../chem.js";

export async function render(el) {
  el.appendChild(h(`<div>
    <p class="lead">В 1869 году Дмитрий Иванович Менделеев расположил 63 известных тогда элемента по возрастанию атомной массы и заметил: свойства <b>периодически повторяются</b>. Так родился периодический закон — главный закон химии.</p>
    ${kid("Менделеев написал каждый элемент на отдельной карточке и раскладывал их, как пасьянс, пока не увидел узор. Говорят, окончательный вариант таблицы ему даже приснился!")}
  </div>`));

  el.appendChild(h(`<section id="history"><h2>Смелые предсказания</h2>
    <p>Менделеев оставил в таблице пустые клетки и предсказал свойства ещё не открытых элементов — «экаалюминия», «экабора», «экасилиция». Через 15 лет их нашли: это галлий (1875), скандий (1879) и германий (1886), и их свойства совпали с предсказанными.</p>
    <div class="table-wrap"><table class="data">
      <tr><th>Свойство «экасилиция»</th><th>Предсказал Менделеев (1871)</th><th>Германий на самом деле (1886)</th></tr>
      <tr><td>Атомная масса</td><td>72</td><td>72,6</td></tr>
      <tr><td>Плотность, г/см³</td><td>5,5</td><td>5,35</td></tr>
      <tr><td>Оксид</td><td>EsO₂, плотность 4,7</td><td>GeO₂, плотность 4,7</td></tr>
    </table></div>
    <div class="callout adv">Сегодня закон формулируют иначе: свойства элементов периодически зависят от <b>заряда ядра</b> (атомного номера), а не от массы. Это объясняет, почему аргон (39,95) стоит перед калием (39,10).</div>
  </section>`));

  el.appendChild(h(`<section id="structure"><h2>Как устроена таблица</h2>
    <ul>
      <li>${term("period", "Период")} — строка. Номер периода = число электронных оболочек.</li>
      <li>${term("group", "Группа")} — столбец. У элементов главных групп одинаковое число ${term("valence", "внешних электронов")}, поэтому они похожи по свойствам.</li>
      <li>${term("block", "Блоки")} s, p, d, f показывают, какой подуровень заполняется.</li>
      <li>Слева и в центре — металлы (их ~80%), справа вверху — неметаллы, по диагонали B–Si–As–Te — ${term("metalloid", "полуметаллы")}.</li>
    </ul>
    <h3>Тренды — как меняются свойства</h3>
    <div class="grid-2">
      <div class="card pad"><b>По периоду слева направо →</b><ul class="small"><li>заряд ядра растёт, электроны притягиваются сильнее</li><li>радиус атома уменьшается</li><li>электроотрицательность растёт</li><li>металлические свойства ослабевают</li></ul></div>
      <div class="card pad"><b>По группе сверху вниз ↓</b><ul class="small"><li>добавляются новые оболочки</li><li>радиус атома растёт</li><li>электроотрицательность падает</li><li>металлические свойства усиливаются</li></ul></div>
    </div>
  </section>`));

  const sec = h(`<section id="city"><h2>Таблица-город в 3D</h2><p>Высота каждой «башни» — значение свойства. Наведи на башню, чтобы узнать элемент. Посмотри, как ${term("en", "электроотрицательность")} растёт к фтору, а плотность «горой» поднимается в центре у осмия и иридия.</p></section>`);
  el.appendChild(sec);
  const chipBox = h(`<div style="margin-bottom:10px"></div>`);
  sec.appendChild(chipBox);
  const st = stage(`<div class="overlay"><span data-hover>Наведи на башню</span></div>`, { wide: true });
  sec.appendChild(st);
  const v = createViewer(st, { camera: [0, 13, 15], fitWidth: 10.5, autoRotate: false, minDistance: 8, maxDistance: 60 });
  const table = createTable3D(v, (e) => {
    st.querySelector("[data-hover]").innerHTML = e
      ? `<b>${e.z}. ${e.name} (${e.sym})</b> · ${CAT_NAMES[e.cat]} · ${PROPS3D[current].label}: <b>${fmt(PROPS3D[current].get(e), 3) ?? "—"}${current === "mp" ? " K" : ""}</b>`
      : "Наведи на башню";
  });
  let current = "en";
  const keys = Object.keys(PROPS3D);
  chips(chipBox, keys.map((k) => ({ k, label: PROPS3D[k].label })), (it) => { current = it.k; table.setProp(it.k); }, 0);
  table.setProp(current);
  sec.appendChild(h(`<p class="small muted" style="margin-top:8px">Температура плавления показана в кельвинах (K = °C + 273), чтобы все высоты были положительными. Полупрозрачные клетки — значение неизвестно.</p>`));
}

