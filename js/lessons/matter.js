const round2 = (x) => { const k = Math.pow(10, Math.floor(Math.log10(x)) - 1); return fmt(Math.round(x / k) * k, 0); };
const sizeLabel = (m) => {
  if (m >= 1e-3) return `${fmt(m * 1000, 1)} мм`;
  if (m >= 1e-6) return `${fmt(m * 1e6, 0)} мкм`;
  return `${fmt(m * 1e9, m >= 1e-9 ? 1 : 2)} нм`;
};

export async function render(el) {
  el.appendChild(h(`<div>
    <p class="lead">Всё вокруг — стол, вода, воздух, ты сам — состоит из веществ. А любое вещество состоит из крошечных частиц: молекул и атомов. Они такие маленькие, что в одной капле воды их больше, чем звёзд во всей видимой Вселенной.</p>
    ${kid("Представь, что у тебя есть волшебная лупа, которая увеличивает в миллион раз. Посмотришь через неё на кусочек сахара — и увидишь, что он сложен из одинаковых «кирпичиков», как дом из конструктора. Эти кирпичики и есть молекулы!")}
  </div>`));

  // ---------- Тела и вещества ----------
  const sec1 = h(`<section id="bodies"><h2>Тела и вещества</h2>
    <p><b>${term("physbody", "Тело")}</b> — это любой предмет: ложка, мяч, капля, снежинка, планета. У тела есть форма, размер, масса. <b>${term("substance", "Вещество")}</b> — это то, <i>из чего</i> сделано тело.</p>
    <div class="grid-2">
      <div class="card pad"><b>Одно вещество — разные тела</b><p class="small">Из стекла делают стакан, бусы, окно и лампочку. Из воды «сделаны» капля, сосулька, облако и снеговик (снег — тоже вода!).</p></div>
      <div class="card pad"><b>Одно тело — разные вещества</b><p class="small">Ложка бывает стальной, деревянной, пластмассовой, серебряной. Форма та же, а вещества разные — и свойства у таких ложек разные.</p></div>
    </div>
    ${kid("Спроси себя: «Что это?» — ответ будет телом (ложка). «Из чего это?» — ответ будет веществом (металл, дерево).", "Как не перепутать")}
    <div class="card pad mt-sort" style="margin-top:14px">
      <b>Тренажёр: тело или вещество?</b>
      <p class="mt-word" aria-live="polite"></p>
      <div class="row"><button class="btn" type="button" data-a="тело">Тело</button><button class="btn" type="button" data-a="вещество">Вещество</button></div>
      <p class="small muted mt-res" style="margin:10px 0 0"></p>
    </div>
  </section>`);
  el.appendChild(sec1);
  {
    const box = sec1.querySelector(".mt-sort");
    let i = 0, ok = 0;
    const show = () => {
      box.querySelector(".mt-word").innerHTML = i < SORT.length ? `Слово ${i + 1} из ${SORT.length}: <b style="font-size:1.3rem">${SORT[i][0]}</b>` : `<b>Готово! Правильно ${ok} из ${SORT.length}.</b> <button class="btn small" type="button" data-again>Ещё раз</button>`;
      box.querySelector("[data-again]")?.addEventListener("click", () => { i = 0; ok = 0; box.querySelector(".mt-res").textContent = ""; show(); });
    };
    box.querySelectorAll("[data-a]").forEach((b) => (b.onclick = () => {
      if (i >= SORT.length) return;
      const [w, ans] = SORT[i];
      const right = b.dataset.a === ans;
      if (right) ok++;
      box.querySelector(".mt-res").innerHTML = right ? `<span style="color:var(--good)">Верно:</span> «${w}» — ${ans}.` : `<span style="color:var(--bad)">Не совсем:</span> «${w}» — это ${ans}.`;
      i++;
      show();
    }));
    show();
  }

  // ---------- Свойства ----------
  const sec2 = h(`<section id="properties"><h2>Свойства веществ</h2>
    <p>Вещества узнают по <b>свойствам</b> — признакам, которые можно увидеть, понюхать, потрогать или измерить: цвет, блеск, запах, твёрдость, растворяется ли в воде, притягивается ли магнитом, при какой температуре плавится и кипит. У каждого вещества свой «паспорт» из свойств.</p>
    <div class="callout warn"><b>Важно:</b> в химии ничего не пробуют на вкус и не нюхают «в упор». Запах проверяют, подгоняя воздух ладонью к носу. Незнакомые вещества трогают только в перчатках и только со взрослыми.</div>
    <div class="mt-chips" style="margin:10px 0"></div>
    <div class="card pad mt-card"></div>
  </section>`);
  el.appendChild(sec2);
  {
    const card = sec2.querySelector(".mt-card");
    const show = (p) => {
      card.innerHTML = `<b style="font-size:1.1rem">${p.n}</b>
        <div class="table-wrap" style="margin-top:8px"><table class="data">
          <tr><td>Цвет и вид</td><td>${p.c}</td></tr><tr><td>Запах</td><td>${p.smell}</td></tr>
          <tr><td>Твёрдость</td><td>${p.hard}</td></tr><tr><td>В воде</td><td>${p.water}</td></tr><tr><td>Магнит</td><td>${p.mag}</td></tr>
        </table></div><p class="small" style="margin:10px 0 0">${p.note}</p>`;
    };
    chips(sec2.querySelector(".mt-chips"), PROPS.map((p) => ({ ...p, label: p.n })), show);
    show(PROPS[0]);
  }
  sec2.appendChild(h(`<p>Соль и сахар на вид почти одинаковые — белые кристаллики. Но если их нагреть, сахар расплавится и потемнеет, а соль останется прежней. Так, сравнивая свойства, химики и отличают одно вещество от другого.</p>`));

  // ---------- 3D-зум ----------
  const sec3 = h(`<section id="zoom"><h2>Путешествие вглубь кубика сахара</h2>
    <p>Двигай ползунок — и мы будем приближаться к кусочку рафинада, каждый раз увеличивая примерно в 10 раз и больше. Покрути сцену мышкой или пальцем.</p></section>`);
  el.appendChild(sec3);
  const st = stage(`<div class="overlay"><span data-t style="font-size:1rem"></span><span data-f></span></div>`, { wide: true });
  sec3.appendChild(st);
  const ctl = h(`<div class="card pad" style="margin-top:10px">
    <label class="ctl">Увеличение<input type="range" min="0" max="4" step="0.01" value="0" aria-label="Увеличение"></label>
    <div class="chips" style="margin-top:10px">${LEVELS.map((l, i) => `<button class="chip${i ? "" : " on"}" type="button" data-l="${i}">${["Кубик", "Кристаллики", "Решётка", "Молекула", "Атом"][i]}</button>`).join("")}</div>
    <p data-d style="margin:12px 0 0"></p>
  </div>`);
  sec3.appendChild(ctl);
  const v = createViewer(st, { camera: [4, 3, 9], minDistance: 4, maxDistance: 24, autoRotateSpeed: 0.6, fitWidth: 3.6 });
  const zoom = createSugarZoom(v);
  const range = ctl.querySelector("input");
  const upd = () => {
    const s = +range.value;
    zoom.set(s);
    const i = Math.round(s);
    st.querySelector("[data-t]").innerHTML = `<b>${LEVELS[i].t}</b>`;
    const f = zoom.field(s);
    st.querySelector("[data-f]").textContent = `поле зрения ≈ ${sizeLabel(f)} · увеличение ×${round2(0.01 / f)}`;
    ctl.querySelector("[data-d]").textContent = LEVELS[i].d;
    ctl.querySelectorAll("[data-l]").forEach((b) => b.classList.toggle("on", +b.dataset.l === i));
  };
  range.oninput = upd;
  ctl.querySelectorAll("[data-l]").forEach((b) => (b.onclick = () => { range.value = b.dataset.l; upd(); }));
  upd();
  sec3.appendChild(h(`<p class="small muted">Цвета атомов — по традиции химиков: углерод тёмно-серый, водород белый, кислород красный. На самом деле у атомов нет цвета: они намного меньше длины волны света.</p>`));

  // ---------- Молекулы и атомы ----------
  const sec4 = h(`<section id="atoms"><h2>Молекулы и атомы</h2>
    <p><b>${term("molecule", "Молекула")}</b> — самая маленькая частица вещества, которая ещё сохраняет его свойства. Молекула сахара сладкая «по-сахарному», а если её разобрать на атомы — получатся углерод, водород и кислород, и сахара уже не будет.</p>
    <p><b>Атомы</b> — «буквы», из которых складываются молекулы-«слова». Разных видов атомов (химических элементов) всего 118, а веществ из них — больше ста миллионов, как слов из 33 букв алфавита.</p>
    <div class="grid-2">
      <div class="card pad"><b>${term("simplesub", "Простые вещества")}</b><p class="small">состоят из атомов одного вида: кислород O₂, азот N₂, водород H₂, железо Fe, алмаз и графит (оба — чистый углерод C).</p></div>
      <div class="card pad"><b>${term("compoundsub", "Сложные вещества")}</b><p class="small">состоят из атомов разных видов: вода H₂O, углекислый газ CO₂, метан CH₄, сахар C₁₂H₂₂O₁₁.</p></div>
    </div>
    <p style="margin-top:14px">Посмотри на несколько молекул в 3D. Формула показывает, какие атомы и сколько их: H₂O — два атома водорода и один атом кислорода.</p>
  </section>`);
  el.appendChild(sec4);
  moleculeExplorer(sec4, ["H2O", "O2", "N2", "CO2", "CH4", "H2"]);

  // ---------- Частицы движутся ----------
  el.appendChild(h(`<section id="motion"><h2>Частицы всё время движутся</h2>
    <p>Молекулы никогда не стоят на месте. В твёрдом теле они дрожат на своих местах, в жидкости — скользят друг мимо друга, в газе — летают со скоростью сотни метров в секунду. Чем теплее, тем быстрее движение. Отсюда три ${term("state", "агрегатных состояния")}: твёрдое, жидкое и газообразное.</p>
    <div class="card pad"><b>Опыт: куда пропадает сахар?</b>
      <ol class="small">
        <li>Налей в два прозрачных стакана воду: в один холодную, в другой тёплую (не кипяток!).</li>
        <li>Одновременно опусти в каждый по кубику сахара и не мешай.</li>
        <li>Наблюдай 5 минут. В тёплой воде сахар исчезает заметно быстрее, а над кубиком видны «струйки».</li>
      </ol>
      <p class="small" style="margin:0">Сахар не исчез: его молекулы разошлись между молекулами воды — это <b>растворение</b>. Вода стала сладкой, и если её выпарить, сахар снова появится. Масса стакана со сладкой водой равна массе воды плюс массе сахара: вещество никуда не пропало.</p>
    </div>
    ${kid("Молекулы — как дети на переменке: когда им «тепло и весело», они бегают быстрее и быстрее разбегаются по всему коридору. Поэтому сахар в тёплом чае растворяется быстрее, чем в холодном.")}
    <div class="callout adv">Масштаб: молекула сахарозы ≈ 1 нм = 0,000 000 001 м. Кубик сахара массой ≈ 3 г содержит 3 / 342 ≈ 0,009 моль, то есть ≈ 5·10²¹ молекул (M(C₁₂H₂₂O₁₁) = 342 г/моль).</div>
  </section>`));
}

